/** 按本地日期取当天题包；没有则返回 null（走正常抽题） */
export function getPackFor(date: string): Pack | null {
  return PACKS.find((p) => p.date === date) ?? null
}

/** 展平题包里的全部题号（按块顺序，块内顺序不变） */
export function packQids(pack: Pack): string[] {
  return pack.blocks.flatMap((b) => b.qids)
}
